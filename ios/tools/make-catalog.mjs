/* Emits the static catalog (plans, movement metadata, injuries, focus areas, cues,
   image names, home sessions...) from the web source so the Swift copy can never
   drift by a typo. Writes:
     ios/StrataCore/Catalog.generated.swift   (the data, embedded as JSON)
     ios/StrataCoreTests/Fixtures/catalog.json (same data, for the golden test)
   Run: node ios/tools/make-catalog.mjs */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadWeb, ROOT} from './webctx.mjs';

export function catalogJSON(run) {
  const c = JSON.parse(run(`JSON.stringify({
    plans:{nr:PLAN_NR,nr3:PLAN_NR3,sa:PLAN_SA,sa3:PLAN_SA3},
    stdFrac:{nr:STD_FRAC_NR,sa:STD_FRAC_SA},
    qmap:{nr:QMAP_NR,sa:QMAP_SA},
    rcQ:RC_Q, areas:AREAS, patLabel:PAT_LABEL, concept:CONCEPT, conceptOf:CONCEPT_OF,
    focus:FOCUS, injuries:INJURIES, exp:EXP, nagDays:NAG_DAYS, plates:PLATES,
    img:IMG, cimg:CIMG, cue:CUE, home:HOME, skipWhy:SKIP_WHY,
    cardioActs:Object.fromEntries(Object.entries(CARDIO_ACTS).map(([k,v])=>[k,{n:v.n,out:v.out}])),
    gridActs:GRID_ACTS, zname:ZNAME, zcol:ZCOL, wcfg:WCFG,
    slotName:SLOT_NAME, ctype:CTYPE, heart:[...HEART], injShow:INJ_SHOW,
    wdShort:WD_S, wdLong:WD_L, wdOrder:WD_ORDER,
    conceptOrder:Object.keys(CONCEPT), focusOrder:Object.keys(FOCUS), injuryOrder:Object.keys(INJURIES)
  })`));
  // JSON has no "present but null"; IMG maps fx_m_fly2 to null (= no photo, no fallback).
  c.imgNone = Object.keys(c.img).filter(k => c.img[k] === null);
  for (const k of c.imgNone) delete c.img[k];
  return c;
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const w = await loadWeb('America/Toronto');
  const cat = catalogJSON(w.run);
  const json = JSON.stringify(cat);
  if (json.includes('"""#')) throw new Error('catalog JSON would break the Swift raw string');
  const swift = `// GENERATED by ios/tools/make-catalog.mjs from core.js / app.js / workout.js. Do not edit.
// Regenerate with: node ios/tools/make-catalog.mjs

enum CatalogSource {
    static let json = #"""
${json}
"""#
}
`;
  fs.writeFileSync(path.join(ROOT, 'ios/StrataCore/Catalog.generated.swift'), swift);
  fs.writeFileSync(path.join(ROOT, 'ios/StrataCoreTests/Fixtures/catalog.json'), JSON.stringify(cat, null, 1) + '\n');
  console.log('catalog written,', json.length, 'bytes');
}
